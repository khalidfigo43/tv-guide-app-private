-- Function: Auto-create profile on Auth signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, email, display_name)
    VALUES (
        new.id,
        new.email,
        COALESCE(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', split_part(new.email, '@', 1))
    );
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Function: Get currently airing broadcasts with progress calculation
CREATE OR REPLACE FUNCTION public.get_now_airing(target_time TIMESTAMPTZ DEFAULT NOW())
RETURNS TABLE (
    broadcast_id BIGINT,
    channel_id BIGINT,
    channel_name VARCHAR,
    channel_name_ar VARCHAR,
    channel_logo TEXT,
    content_id BIGINT,
    content_title_ar VARCHAR,
    content_title_en VARCHAR,
    content_type VARCHAR,
    release_year INT,
    rating NUMERIC,
    poster_path TEXT,
    backdrop_path TEXT,
    overview_ar TEXT,
    start_datetime TIMESTAMPTZ,
    end_datetime TIMESTAMPTZ,
    remaining_minutes INT,
    progress_percent INT
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        b.id AS broadcast_id,
        c.id AS channel_id,
        c.name AS channel_name,
        c.name_ar AS channel_name_ar,
        c.logo_url AS channel_logo,
        cnt.id AS content_id,
        cnt.title_ar AS content_title_ar,
        cnt.title_en AS content_title_en,
        cnt.content_type,
        cnt.release_year,
        cnt.rating,
        cnt.poster_path,
        cnt.backdrop_path,
        cnt.overview_ar,
        b.start_datetime,
        b.end_datetime,
        CASE 
            WHEN b.end_datetime IS NOT NULL AND b.end_datetime > target_time 
            THEN EXTRACT(EPOCH FROM (b.end_datetime - target_time))::INT / 60
            ELSE 0
        END AS remaining_minutes,
        CASE 
            WHEN b.end_datetime IS NOT NULL AND b.end_datetime > b.start_datetime
            THEN LEAST(100, GREATEST(0, (EXTRACT(EPOCH FROM (target_time - b.start_datetime)) * 100 / EXTRACT(EPOCH FROM (b.end_datetime - b.start_datetime)))::INT))
            ELSE 0
        END AS progress_percent
    FROM public.broadcasts b
    JOIN public.channels c ON b.channel_id = c.id
    JOIN public.content cnt ON b.content_id = cnt.id
    WHERE b.start_datetime <= target_time 
      AND (b.end_datetime IS NULL OR b.end_datetime > target_time)
      AND c.is_active = TRUE
    ORDER BY c.display_order ASC, c.name ASC;
END;
$$ LANGUAGE plpgsql STABLE;

