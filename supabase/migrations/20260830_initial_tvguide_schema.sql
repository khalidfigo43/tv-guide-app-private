-- =============================================================================
-- TV Guide Online Application - Production Database Schema (Supabase PostgreSQL)
-- =============================================================================

-- Enable required extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pg_trgm";

-- =============================================================================
-- 1. CHANNELS TABLE
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.channels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    name_ar VARCHAR(255),
    name_en VARCHAR(255),
    logo_url TEXT,
    source VARCHAR(100) DEFAULT 'rotana',
    source_channel_id VARCHAR(100),
    country VARCHAR(100) DEFAULT 'SA',
    language VARCHAR(20) DEFAULT 'ar',
    category VARCHAR(100) DEFAULT 'entertainment',
    is_active BOOLEAN DEFAULT TRUE,
    display_order INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    CONSTRAINT uq_channel_source_id UNIQUE (source, source_channel_id)
);

-- =============================================================================
-- 2. CHANNEL FREQUENCIES TABLE
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.channel_frequencies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id BIGINT NOT NULL REFERENCES public.channels(id) ON DELETE CASCADE,
    satellite VARCHAR(100) NOT NULL, -- e.g. 'Nilesat 7.0°W', 'Arabsat Badr-8 26.0°E'
    frequency VARCHAR(50) NOT NULL,  -- e.g. '12226'
    polarization VARCHAR(20) NOT NULL, -- 'H' (Horizontal) or 'V' (Vertical)
    symbol_rate VARCHAR(50) NOT NULL, -- e.g. '27500'
    fec VARCHAR(50) DEFAULT '5/6',   -- e.g. '5/6', '3/4', 'Auto'
    quality VARCHAR(50) DEFAULT 'HD', -- 'HD', 'SD'
    system VARCHAR(50) DEFAULT 'DVB-S2', -- 'DVB-S', 'DVB-S2'
    is_encrypted BOOLEAN DEFAULT FALSE,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- =============================================================================
-- 3. CONTENT TABLE (CANONICAL IDENTITY)
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.content (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_type VARCHAR(30) NOT NULL DEFAULT 'unknown', -- 'movie', 'series', 'program', 'unknown'
    title_ar VARCHAR(500) NOT NULL,
    title_en VARCHAR(500),
    original_title VARCHAR(500),
    normalized_title VARCHAR(500) NOT NULL,
    release_year INT,
    tmdb_id BIGINT,
    tmdb_type VARCHAR(20), -- 'movie', 'tv'
    poster_path TEXT,      -- Path only: e.g. '/9InvbMsehKRhHMSbPvAJrK0boCz.jpg' (CDN loaded)
    backdrop_path TEXT,    -- Path only: e.g. '/gyWQES8SdLH7pwNReQnpqu7Pz7x.jpg'
    overview_ar TEXT,
    overview_en TEXT,
    rating NUMERIC(3, 1),
    genres JSONB DEFAULT '[]'::jsonb,
    cast_members JSONB DEFAULT '[]'::jsonb,
    runtime_minutes INT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- =============================================================================
-- 4. CONTENT EXTERNAL IDS (Source mapping, e.g. Rotana item ID, TMDB, IMDB)
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.content_external_ids (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_id BIGINT NOT NULL REFERENCES public.content(id) ON DELETE CASCADE,
    provider VARCHAR(100) NOT NULL, -- 'rotana', 'tmdb', 'imdb', 'elcinema'
    external_id VARCHAR(255) NOT NULL,
    external_type VARCHAR(100), -- 'schedule_item', 'tmdb_movie', 'tmdb_tv'
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    CONSTRAINT uq_content_provider_external_id UNIQUE (provider, external_id)
);

-- =============================================================================
-- 5. CONTENT ALIASES (Alternative titles for robust search & matching)
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.content_aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_id BIGINT NOT NULL REFERENCES public.content(id) ON DELETE CASCADE,
    title VARCHAR(500) NOT NULL,
    normalized_title VARCHAR(500) NOT NULL,
    language VARCHAR(20) DEFAULT 'ar',
    source VARCHAR(100),
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- =============================================================================
-- 6. BROADCASTS TABLE
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.broadcasts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id BIGINT NOT NULL REFERENCES public.channels(id) ON DELETE CASCADE,
    content_id BIGINT NOT NULL REFERENCES public.content(id) ON DELETE CASCADE,
    source VARCHAR(100) DEFAULT 'rotana',
    source_item_id VARCHAR(100),
    broadcast_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME,
    start_datetime TIMESTAMPTZ NOT NULL,
    end_datetime TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    CONSTRAINT uq_broadcast_channel_source_time UNIQUE (channel_id, source, source_item_id, start_datetime)
);

-- =============================================================================
-- 7. USER PROFILES & FAVORITES (Supabase Auth integration)
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT,
    display_name TEXT,
    avatar_url TEXT,
    preferred_language VARCHAR(10) DEFAULT 'ar',
    timezone VARCHAR(50) DEFAULT 'Asia/Riyadh',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.favorite_movies (
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    content_id BIGINT NOT NULL REFERENCES public.content(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    PRIMARY KEY (user_id, content_id)
);

CREATE TABLE IF NOT EXISTS public.favorite_channels (
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    channel_id BIGINT NOT NULL REFERENCES public.channels(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    PRIMARY KEY (user_id, channel_id)
);

-- =============================================================================
-- 8. MANUAL IDENTITY REVIEW OVERRIDES
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.identity_review_overrides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_title VARCHAR(500) NOT NULL,
    normalized_source_title VARCHAR(500) NOT NULL UNIQUE,
    tmdb_id BIGINT,
    tmdb_type VARCHAR(20), -- 'movie', 'tv', 'none'
    content_type VARCHAR(30), -- 'movie', 'series', 'program'
    notes TEXT,
    reviewed_by VARCHAR(100),
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- =============================================================================
